import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { setup, signIn, BASE_URL } from '../helpers/harness.ts';

test('Calendar shares Estimate/Actual dates, supports filters and editing, and respects viewer access', async () => {
  const fx = await setup();
  let browser;
  try {
    await fx.client.query(`UPDATE pmt_nodes SET node_name='Calendar test task', node_estimate_start='2026-10-12', node_estimate_end='2026-10-14', node_actual_start='2026-10-15', node_actual_end='2026-10-16' WHERE node_id=$1`, [fx.nodes.task]);
    await fx.client.query(`UPDATE pmt_nodes SET node_name='Unscheduled calendar task', node_estimate_start=NULL, node_estimate_end=NULL, node_actual_start=NULL, node_actual_end=NULL WHERE node_id=$1`, [fx.nodes.sub]);
    const result = await fx.client.query('SELECT project_slug FROM pmt_projects WHERE project_id=$1', [fx.projectId]);
    const slug = result.rows[0].project_slug;
    const admin = await signIn(fx.admin.email, fx.admin.password);
    const viewer = await signIn(fx.viewer.email, fx.viewer.password);
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const cookies = (header: string) => header.split('; ').map(pair => {
      const at = pair.indexOf('='); return { name: pair.slice(0,at), value: pair.slice(at+1), url: BASE_URL };
    });
    await context.addCookies(cookies(admin.header));
    const page = await context.newPage();
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${BASE_URL}/p/${slug}/calendar?node=${fx.nodes.task}`);
    const modal = page.getByRole('dialog', { name: 'Task details' });
    await expect(modal).toBeVisible();
    await expect(modal.getByLabel('Estimate end', { exact: true })).toHaveValue('2026-10-14');
    await modal.getByRole('button', { name: 'Close task details' }).click();
    await page.getByRole('searchbox', { name: 'Search calendar tasks' }).fill('Calendar test task');
    const est = page.locator(`.cal-bars button[data-node="${fx.nodes.task}"][data-kind="estimate"]`);
    const act = page.locator(`.cal-bars button[data-node="${fx.nodes.task}"][data-kind="actual"]`);
    await expect(est).toHaveCount(1); await expect(act).toHaveCount(1);
    await page.getByRole('button', { name: 'Estimate', exact: true }).click();
    await expect(act).toHaveCount(0); await expect(est).toHaveCount(1);
    await page.getByRole('button', { name: 'Actual', exact: true }).click();
    await expect(est).toHaveCount(0); await expect(act).toHaveCount(1);
    await page.getByRole('button', { name: 'Both', exact: true }).click();
    await page.getByRole('checkbox', {name:'Module',exact:true}).uncheck();
    await expect(est).toHaveCount(0); await expect(act).toHaveCount(0);
    await page.getByRole('button', {name:'Show all',exact:true}).click();
    await expect(est).toHaveCount(1);
    await page.getByRole('button', {name:'Next month',exact:true}).click();
    await expect(page.getByText('No dates in this month.',{exact:false})).toBeVisible();
    await page.getByRole('button', {name:'Previous month',exact:true}).click();
    await expect(est).toHaveCount(1);
    await est.click();
    await expect(modal.getByLabel('Task name', { exact:true })).toHaveValue('Calendar test task');
    await modal.getByLabel('Estimate end', { exact:true }).fill('2026-10-13');
    await modal.getByRole('button', { name:'Save changes' }).click();
    await expect(modal).not.toBeVisible();
    const afterSave = await fx.client.query('SELECT node_estimate_end FROM pmt_nodes WHERE node_id=$1', [fx.nodes.task]);
    assert.equal(afterSave.rows[0].node_estimate_end, '2026-10-13');
    await expect(est).toHaveAttribute('title', /2026-10-13/);
    await expect(act).toHaveAttribute('title', /2026-10-15 → 2026-10-16/);
    const stored = await fx.client.query('SELECT node_estimate_end, node_actual_start, node_actual_end FROM pmt_nodes WHERE node_id=$1', [fx.nodes.task]);
    assert.deepEqual(stored.rows[0], {node_estimate_end:'2026-10-13',node_actual_start:'2026-10-15',node_actual_end:'2026-10-16'});
    await page.getByRole('searchbox', {name:'Search calendar tasks'}).fill('');
    await page.getByRole('button', {name:/^Unscheduled/}).click();
    await page.getByRole('button', {name:/Unscheduled calendar task/}).click();
    await expect(modal.getByLabel('Actual start', {exact:true})).toHaveValue('');
    await modal.getByRole('button', {name:'Close task details'}).click();
    await page.getByRole('button', {name:'Close day schedules'}).click();
    await page.getByRole('searchbox', {name:'Search calendar tasks'}).fill('Calendar test task');
    await page.getByRole('button', {name:'14 Oct 2026',exact:true}).click();
    await page.getByRole('button', {name:'Close day schedules'}).click();
    await page.getByLabel('Calendar view', {exact:true}).selectOption('week');
    await expect(est).toHaveCount(1); await expect(act).toHaveCount(1);
    await page.getByLabel('Calendar view', {exact:true}).selectOption('month');
    await page.screenshot({path:'.work/calendar-desktop.png',fullPage:true});
    await expect(page.getByRole('navigation',{name:'Project views'}).getByRole('link',{name:'List',exact:true})).toBeVisible();
    await page.getByRole('link',{name:'List',exact:true}).click();
    await expect(page.getByRole('link',{name:'Calendar',exact:true})).toBeVisible();
    await page.getByRole('link',{name:'Calendar',exact:true}).click();
    await expect(page.getByRole('main',{name:'Project calendar'})).toBeVisible();
    await context.clearCookies(); await context.addCookies(cookies(viewer.header));
    await page.goto(`${BASE_URL}/p/${slug}/calendar?node=${fx.nodes.task}`);
    await expect(modal.getByLabel('Estimate end',{exact:true})).toBeDisabled();
    await expect(modal.getByRole('button',{name:'Save changes'})).toHaveCount(0);
    await modal.getByRole('button',{name:'Close task details'}).click();
    await page.setViewportSize({width:390,height:844});
    await page.reload();
    await expect(page.getByLabel('Toggle calendar sidebar')).toHaveAttribute('aria-expanded','false');
    const size = await page.evaluate(() => ({w:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert.ok(size.w <= size.viewport, 'only the calendar grid scrolls horizontally on mobile');
    await page.screenshot({path:'.work/calendar-mobile.png',fullPage:true});
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await fx.cleanup(); }
});
